# --- cluster size computation ---
cluster_data = []

for (subject, domain), group in df_paired.groupby(['subject_id', 'domain']):
    distances = group['spam_distance'].tolist()
    if len(distances) == 0:
        continue

    threshold = np.median(distances)

    cluster_sizes = []
    current_size = 1

    for dist in distances:
        if dist < threshold:
            current_size += 1
        else:
            cluster_sizes.append(current_size)
            current_size = 1

    cluster_sizes.append(current_size)

    cluster_data.append({
        'subject_id': subject,
        'mean_cluster_size': np.mean(cluster_sizes)
    })

df_clusters = pd.DataFrame(cluster_data).groupby('subject_id').mean().reset_index()

