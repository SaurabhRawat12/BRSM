latency_rows = []
for _, row in df_vft_main.iterrows():
    min_len = min(len(row['words']), len(row['irts']))
    for i in range(min_len):
        latency_rows.append({
            'subject_id' : row['subject_id'],
            'domain'     : row['domain'],
            'word'       : row['words'][i],
            'latency_ms' : row['irts'][i]
        })
word_latency_df = pd.DataFrame(latency_rows)

# word-level SpAM coordinates
rows = []
for _, r in df_spam_main.iterrows():
    for w in r['word_coords']:
        rows.append({
            'subject_id' : r['subject_id'],
            'domain'     : r['domain'],
            'word'       : w['word'],
            'x'          : w['x'],
            'y'          : w['y']
        })
wc = pd.DataFrame(rows)

# mean neighbour distance per word (density proxy)
dens_list = []
for (s, d), g in wc.groupby(['subject_id', 'domain']):
    coords = g[['x', 'y']].values
    if len(coords) < 2:
        continue
    distmat  = squareform(pdist(coords))
    tmp = g.copy()
    tmp['mean_neighbor_dist'] = distmat.mean(axis=1)
    dens_list.append(tmp)

word_density = pd.concat(dens_list, ignore_index=True)
merged = pd.merge(word_latency_df, word_density,
                  on=['subject_id', 'domain', 'word'], how='inner')
merged = merged[(merged['latency_ms'] > 0) & (merged['latency_ms'] < 30000)].dropna()

print("="*60)
print("RQ2: Semantic Neighbourhood Density  (non-practice trials)")
print("="*60)
print(f"Word-level rows: {len(merged)}")

if len(merged) > 2:
    r_density, p_density = pearsonr(np.log1p(merged['latency_ms']),
                                    merged['mean_neighbor_dist'])
    print(f"\nPearson r  (log(1+IRT) vs mean_neighbor_dist):")
