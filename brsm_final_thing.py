                word_coords_dict = {}
                for item in dropped_words:
                    if isinstance(item, dict):
                        word = item.get('word')
                        x = item.get('x_norm')
                        y = item.get('y_norm')
                        if word is not None and x is not None and y is not None:
                            word_coords_dict[word] = {'word': word, 'x': x, 'y': y}

                word_coords = list(word_coords_dict.values())
                pairwise_distances = []

